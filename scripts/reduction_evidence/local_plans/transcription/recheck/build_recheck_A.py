def load(code):
    rows = []
    for r in csv.DictReader(open(SRC, encoding="utf-8-sig", newline="")):
        if r["지역_코드"] == code:
            rows.append({c: (r.get(c) or "").strip() for c in COLUMNS})
    return rows


def unflag(text):
    return text.replace(FLAG, "").replace("확인 필요(그림 판독)", "").strip()


