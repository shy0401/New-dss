def diff(code, prev, new, reasons):
    lines = []
    old = {r["과제_번호"]: r for r in prev}
    cur = {r["과제_번호"]: r for r in new}
    for no, r in cur.items():
        if no not in old:
            lines.append([code, no, r["과제_이름"], "(행 전체)", "", f"{r['부문']} 부문 / 수단 {r['수단_ID']} / 예산 {r['예산']}", r["쪽"], "행 추가", r["비고"]])
            continue
        for c in COLUMNS:
            a, b = old[no][c], r[c]
            if a == b:
                continue
            if c == "수단_ID":
                kind = "수단 고침"
            elif not a and b:
                kind = "빈칸 채움"
            else:
                kind = "값 고침"
            if (no, c) in reasons:
                why = reasons[(no, c)]
            elif c in RECORD_COLUMNS:
                why = RECORD_COLUMNS[c]
            elif c == "목표_단위":
                why = UNIT_NOTE if a else "표 머리의 단위"
            elif c == "목표_연도":
                why = "표 머리의 연도"
            else:
                why = "원문 글자와 대조"
            lines.append([code, no, r["과제_이름"], c, a, b, r["쪽"], kind, why])
    for no, r in old.items():
        if no not in cur:
            lines.append([code, no, r["과제_이름"], "(행 전체)", f"{r['부문']} 부문", "", r["쪽"], "행 삭제", "원문에 없음"])
    return lines


def write(path, header, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def check(code, rows):
    problems = []
    for i, r in enumerate(rows, 2):
        if list(r) != COLUMNS:
            problems.append(f"{code}:{i} 열 순서")
        bad = [m for m in re.split(r";\s*", r["수단_ID"]) if m not in MEASURES]
        if bad:
            problems.append(f"{code}:{i} 수단_ID {bad}")
        if r["값의_종류"] != KIND:
            problems.append(f"{code}:{i} 값의_종류")
        if r["목표_감축량"] and not (r["목표_단위"] and r["목표_연도"]):
            problems.append(f"{code}:{i} 단위 · 연도 없음")
        if "그림 판독" in r["비고"] or "미리보기" in r["본_범위"] or "쪽 그림" in r["본_범위"]:
            problems.append(f"{code}:{i} 그림 판독 표시가 남음")
        if not r["본_범위"].startswith("전문(원문 PDF 글자, 읽은 쪽:"):
            problems.append(f"{code}:{i} 본_범위 형식")
        if "download/BOARD_ATTACH?storageNo=" not in r["출처_주소"]:
            problems.append(f"{code}:{i} 출처 주소")
    if len({r["과제_번호"] for r in rows}) != len(rows):
        problems.append(f"{code} 과제 번호 겹침")
    return problems


