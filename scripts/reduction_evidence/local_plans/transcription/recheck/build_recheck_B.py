def load_old(code):
    """앞선 표의 그 지역 행. 합치기(merge_plans.py)가 '참고(원문 대조 전)' 행 가운데 값이 있는 행의
    비고에 붙이던 '확인 필요(그림 판독)'도 똑같이 붙여, 대조 전 합친 표와 같은 값으로 만든다."""
    name, image_read = OLD_SOURCE[code]
    with open(os.path.join(HERE, "..", name), encoding="utf-8-sig", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["지역_코드"] == code]
    if image_read:
        for r in rows:
            if any(r[c] for c in ("목표_감축량", "예산", "실적_2025")) and "그림 판독" not in r["비고"]:
                r["비고"] = " / ".join(x for x in (r["비고"], "확인 필요(그림 판독)") if x)
    return rows


def write_csv(name, cols, rows):
    path = os.path.join(HERE, name)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in cols})
    return path


def diff(code, old_rows, new_rows, key=lambda r: r["과제_번호"]):
    """한 칸에 한 줄. 앞선 표에만 있는 행은 '행 삭제', 새 표에만 있는 행은 '행 추가'."""
    out = []
    old_by = {key(r): r for r in old_rows}
    new_by = {key(r): r for r in new_rows}
    for k, o in old_by.items():
        if k not in new_by:
            out.append({"지역_코드": code, "과제_번호": o["과제_번호"], "과제_이름": o["과제_이름"], "열": "",
                        "앞선_값": o["과제_이름"], "원문_값": "", "쪽": o["쪽"], "종류": "행 삭제",
                        "비고": o.get("_del_note", "")})
    for k, n in new_by.items():
        if k not in old_by:
            summ = "감축 %s %s(%s) / 예산 %s" % (n["목표_감축량"] or "없음", n["목표_단위"], n["목표_연도"] or "-",
                                              n["예산"] or "없음")
            out.append({"지역_코드": code, "과제_번호": n["과제_번호"], "과제_이름": n["과제_이름"], "열": "",
                        "앞선_값": "", "원문_값": summ, "쪽": n["쪽"], "종류": "행 추가",
                        "비고": n.get("_add_note", "")})
            continue
        o = old_by[k]
        for c in COLS:
            if (o.get(c) or "") == (n.get(c) or ""):
                continue
            if c == "수단_ID":
                kind = "수단 고침"
            elif not (o.get(c) or ""):
                kind = "빈칸 채움"
            else:
                kind = "값 고침"
            note = n.get("_notes", {}).get(c, "")
            if not note and c in PROVENANCE:
                note = "출처 · 읽은 범위 · 메모 표기가 바뀜(과제의 값이 아님)"
            out.append({"지역_코드": code, "과제_번호": n["과제_번호"], "과제_이름": n["과제_이름"], "열": c,
                        "앞선_값": o.get(c) or "", "원문_값": n.get(c) or "", "쪽": n["쪽"], "종류": kind,
                        "비고": note})
    return out


def check_rows(rows):
    for r in rows:
        assert r["값의_종류"] == KIND, r["과제_번호"]
        for m in r["수단_ID"].split(";"):
            assert m in ALLOWED, (r["과제_번호"], m)
        assert r["본_범위"].startswith("전문(원문 PDF 글자, 읽은 쪽:"), r["과제_번호"]
        assert "확인 필요(그림 판독)" not in r["비고"], r["과제_번호"]
        if r["목표_감축량"]:
            assert r["목표_단위"] and r["목표_연도"], r["과제_번호"]
        else:
            assert not r["목표_단위"] and not r["목표_연도"], r["과제_번호"]


