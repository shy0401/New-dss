def load(code):
    with open(SRC, encoding="utf-8-sig", newline="") as f:
        return [{c: r[c] for c in COLS} for r in csv.DictReader(f) if r["지역_코드"] == code]


def page_key(tok):
    m = re.match(r"\s*(\d+)", tok)
    return int(m.group(1)) if m else 10 ** 6


def merge_pages(old, *more):
    toks = [t.strip() for t in old.split(",") if t.strip()]
    for m in more:
        if m and m not in toks:
            toks.append(m)
    return ", ".join(sorted(toks, key=page_key))


def strip_tag(note):
    return note.replace(TAG, "").strip()


def write_csv(path, cols, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)


def diff(code, pairs, removed, custom, content_fill=False):
    """pairs: [(old_row|None, new_row)], removed: [old_row]. custom: {(과제_번호, 열): 비고}."""
    out = []
    # 모든 행에서 같은 식으로 바뀐 열은 한 줄로
    n_old = sum(1 for o, _ in pairs if o is not None)
    for col in UNIFORM:
        chg = {}
        for o, n in pairs:
            if o is not None and o[col] != n[col]:
                chg.setdefault((o[col], n[col]), []).append(n["과제_번호"])
        for (o, n), keys in chg.items():
            who = "(전체 행)" if len(keys) == n_old else f"(행 {len(keys)}개: {keys[0]}~{keys[-1]})"
            out.append({"지역_코드": code, "과제_번호": who, "과제_이름": "", "열": col, "앞선_값": o,
                        "원문_값": n, "쪽": "", "종류": "값 고침",
                        "비고": custom.get(("*", col), DEFAULT_NOTE.get(col, ""))})
    for old, new in pairs:
        key = new["과제_번호"]
        if old is None:
            out.append({"지역_코드": code, "과제_번호": key, "과제_이름": new["과제_이름"], "열": "(행)",
                        "앞선_값": "", "원문_값": "; ".join(f"{c}={new[c]}" for c in
                                                         ("부문", "목표_감축량", "목표_단위", "목표_연도", "예산", "수단_ID")
                                                         if new[c]),
                        "쪽": new["쪽"], "종류": "행 추가", "비고": custom.get((key, "(행)"), "")})
            continue
        for col in COLS:
            if old[col] == new[col]:
                continue
            if col in UNIFORM:
                continue
            if col in ("수단_ID", "층"):
                kind = "수단 고침"
            elif old[col] == "" or (content_fill and col == "과제_내용"):
                kind = "빈칸 채움"
            else:
                kind = "값 고침"
            note = custom.get((key, col), DEFAULT_NOTE.get(col, ""))
            if content_fill and col == "과제_내용" and not note:
                note = "앞선 값은 사업물량뿐이라 과제 설명을 원문 글자로 채움"
            out.append({"지역_코드": code, "과제_번호": key, "과제_이름": new["과제_이름"], "열": col,
                        "앞선_값": old[col], "원문_값": new[col], "쪽": new["쪽"], "종류": kind, "비고": note})
    for old in removed:
        out.append({"지역_코드": code, "과제_번호": old["과제_번호"], "과제_이름": old["과제_이름"], "열": "(행)",
                    "앞선_값": old["과제_이름"], "원문_값": "", "쪽": old["쪽"], "종류": "행 삭제", "비고": ""})
    return out


def report(code, old_rows, new_rows, changes):
    from collections import Counter
    print(f"\n===== {code}: 행 {len(old_rows)} → {len(new_rows)}, 달라진 줄 {len(changes)}")
    print("  종류별:", dict(Counter(c["종류"] for c in changes)))
    print("  열별:", dict(Counter(c["열"] for c in changes)))


def num(s):
    return float(s.replace(",", ""))


