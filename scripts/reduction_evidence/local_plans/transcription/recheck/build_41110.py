    for c in d["comps"]:
        lab = f"[{c['label']}] " if c["label"] else ""
        if c["cum"]:
            p.append(f"{lab}감축잠재량(tCO2eq, 누적) " + seq(c["cum"]))
            p.append(f"{lab}감축잠재량(tCO2eq, 당해) " + seq(c["single"]))
