def budget_text(d, with_ba=True):
    parts = []
    if with_ba:
        ba = d["ba"]
        if all(v == "-" for v in ba):
            parts.append("비예산(과제카드 '※ 비예산'; 건물 부문 재정투자 계획 표도 모든 연도 '-')")
        else:
            parts.append(f"2025~2029년 계 {ba[5]}백만 원(건물 부문 '바. 재정투자 계획' 표, 단위 백만 원: "
                         + " · ".join(f"{y} {v}" for y, v in zip(YEARS[:5], ba[:5])) + ")")
    if d.get("card"):
        parts.append("과제카드 '연도별 재정투자 계획' 합계 줄(백만원): " + yl(d["card"])
                     + (f" / 재원: {d['src']}" if d.get("src") else ""))
    return "; ".join(parts)


def note_text(d, in_sector=True):
    p = [f"사업유형 {d['new']} · 감축유형 {d['typ']} · 사업기간 {d['period']}(과제카드)"]
    if d["single"]:
        p.append("과제카드 감축잠재량(tCO₂eq.) 단년: " + yl(d["single"]))
    if d["cum"]:
        p.append("누적: " + yl(d["cum"]))
    elif d["single"]:
        p.append("누적 줄은 모든 연도 '-'(그해 값만 있음)")
    if d["goal"]:
        p.append(f"과제카드 '온실가스 감축 목표('25~'34)': {d['goal']} tCO₂eq.")
    if not d["single"]:
        p.append("정성 과제: 감축량이 문서에 없음(표 107 · 과제카드 모두 '-')")
    if d.get("unit"):
        p.append("감축원단위: " + d["unit"])
    if d.get("ind"):
        p.append("사업지표: " + d["ind"])
    if in_sector:
        ba, card = d["ba"], d.get("card")
        if card and ba[:5] != card[:5]:
            p.append("예산이 두 표에서 다름: 재정투자 계획 표(183~185쪽)와 과제카드의 '25~'29 값이 같지 않음(둘 다 문서 그대로 예산 열에 적음)")
    else:
        p.append("건물 부문 밖 과제(건물에 직접 붙는 사업이라 규칙 3절에 따라 넣음). 건물 부문 합계(469,465 tCO₂eq.)에는 들어 있지 않음")
    if d.get("note"):
        p.append(d["note"])
    return ". ".join(p)


