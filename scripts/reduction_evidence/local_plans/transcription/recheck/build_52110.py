def num(s):
    return None if s in ("-", "", None) else float(s.replace(",", ""))


def checks():
    print("== 점검(문서의 합계와 맞는지) ==")
    print("건물 과제 수:", len(T), "/ 정량:", sum(1 for d in T if d["typ"] == "정량"),
          "/ 정성:", sum(1 for d in T if d["typ"] == "정성"))
    # 1) 표 107의 2030년 값 합
    s107 = sum(num(d["t107"]) or 0 for d in T)
    print("표 107 건물 2030년 값의 합:", s107)
    # 2) '마' 표 방식: 누적 줄이 있으면 누적, 없으면 단년
    printed = {"'25": 11115, "'26": 46980, "'27": 117237, "'28": 175675, "'29": 234359, "'30": 469465, "'34": 662573}
    for y, pv in printed.items():
        i = YEARS.index(y)
        tot = 0
        for d in T:
            if not d["single"]:
                continue
            v = num((d["cum"] or d["single"])[i])
            tot += v or 0
        print(f"  {y}: 과제카드 값의 합(누적 있으면 누적, 없으면 단년) {tot:,.0f} / 문서 합계 {pv:,} / 차 {tot - pv:,.0f}")
    # 3) 예산: 바 표
    pb = [91138, 275553, 566527, 602155, 666218, 2201591]
    for i, lab in enumerate(YEARS[:5] + ["계"]):
        tot = sum(num(d["ba"][i]) or 0 for d in T)
        print(f"  재정투자 표 {lab}: 과제 줄의 합 {tot:,.0f} / 문서 '합 계' {pb[i]:,} / 차 {tot - pb[i]:,.0f}")
    # 4) 과제카드 예산 합과 표 125(억원)
    t125 = [907, 2751, 5661, 6017, 6658, 6651]
    for i in range(6):
        tot = sum(num(d["card"][i]) or 0 for d in T if d.get("card"))
        print(f"  과제카드 합계 줄의 합 {YEARS[i]}: {tot:,.0f}백만 원 = {tot / 100:,.1f}억 원 / 표 125 건물 소계 {t125[i]:,}억원")
    tot = sum(sum(num(v) or 0 for v in d["card"][6:]) for d in T if d.get("card"))
    print(f"  과제카드 합계 줄의 합 '31~'34: {tot:,.0f}백만 원 = {tot / 100:,.1f}억 원 / 표 125 건물 소계 24,647억원")


